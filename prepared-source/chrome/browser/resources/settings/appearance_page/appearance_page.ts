  override willUpdate(changedProperties: PropertyValues<this>) {
    super.willUpdate(changedProperties);

    const changedPrivateProperties =
        changedProperties as Map<PropertyKey, unknown>;

    if (changedPrivateProperties.has('noventraSpaces_') &&
        !this.activeSpaces_().some(space => space.id === this.noventraRouteSpace_)) {
      this.noventraRouteSpace_ = '';
    }

    if (changedPrivateProperties.has('defaultFontSizePref_')) {
      this.defaultFontSizeChanged_();
    }

    // <if expr="is_linux">
    if (changedPrivateProperties.has('themeSystemThemePref_')) {
      this.systemTheme_ = this.themeSystemThemePref_!.value;
    }
    // </if>

    if (changedPrivateProperties.has('themeIdPref_') ||
        changedPrivateProperties.has('systemTheme_') ||
        changedPrivateProperties.has('themePolicyColorPref_')
        // <if expr="is_linux">
        || changedPrivateProperties.has('themeSystemThemePref_')
        // </if>
    ) {
      this.themeChanged_();
    }

    if (changedPrivateProperties.has('pinnedActionsPref_') ||
        changedPrivateProperties.has('showHomeButtonPref_') ||
        changedPrivateProperties.has('showForwardButtonPref_') ||
        changedPrivateProperties.has('pinSplitTabButtonPref_') ||
        changedPrivateProperties.has('pinContextualTaskButtonPref_')) {
      this.toolbarPinningStateChanged_();
    }
  }

  override updated(changedProperties: PropertyValues<this>) {
    super.updated(changedProperties);
    // Native selection makes option selected-attributes stop updating the
    // displayed value. Reconcile properties after render, including a rejected
    // change whose authoritative preference value has remained unchanged.
    const visibility = this.noventraBarVisibilityMode_();
    for (const [id, hidden] of [
           ['noventraSidebarVisibility', ['sidebars', 'all'].includes(visibility)],
           ['noventraTopVisibility', ['top', 'all'].includes(visibility)],
         ] as const) {
      const select = this.shadowRoot.querySelector<HTMLSelectElement>(`#${id}`);
      if (select) {
        select.value = hidden ? 'edge' : 'visible';
      }
    }
    const changed = changedProperties as Map<PropertyKey, unknown>;
    if (changed.has('noventraSection_') || changed.has('noventraSearchMode')) {
      void this.refreshWorkspaceSync_();
    }
    if (changed.has('noventraSpaces_') || changed.has('noventraRouteSpace_')) {
      // Reconcile after the option list changes: an unchanged Lit value
      // binding alone does not repair the browser's selected option.
      const select = this.shadowRoot.querySelector<HTMLSelectElement>('#noventraRouteSpace');
      if (select) select.value = this.noventraRouteSpace_;
    }
  }

