  protected async onSpaceAppearanceChange_(event: Event) {
    const select = event.currentTarget as HTMLSelectElement;
    const id = select.dataset['space'] || '';
    const space = this.noventraSpaces_.find(item => item.id === id);
    const field = select.dataset['appearance'];
    if (!space || !space.appearanceEditable || this.noventraSpacesPending_ ||
        (field !== 'color' && field !== 'icon' && field !== 'theme') ||
        (field === 'theme' && !space.themeEditable)) {
      return;
    }
    // Send only the changed field. Native code merges it with the latest saved
    // appearance, including edits made in another Settings window.
    const saved = await this.updateSpaces_(
        'appearance', id, JSON.stringify({[field]: select.value}));
    if (!this.isConnected) return;
    if (saved) {
      this.noventraSpaceStatus_ = field === 'theme' ?
          `Theme saved for ${space.name}. It applies when you use this space.` :
          `Appearance saved for ${space.name}.`;
    }
    await this.updateComplete;
    // A rejected native mutation must restore the displayed saved choice.
    const current = this.noventraSpaces_.find(item => item.id === id);
    if (current && select.isConnected) {
      select.value = current[field];
      select.focus();
    }
  }

