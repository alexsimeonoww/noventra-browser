  protected workspaceSyncStatus_(): string {
    if (this.noventraSyncDisconnecting_) return 'Disconnecting…';
    if (this.noventraSync_.state === 'catching_up' ||
        this.noventraSync_.error === 'sync_catching_up') {
      return WORKSPACE_SYNC_CATCH_UP_MESSAGE;
    }
    if (this.noventraSyncBusy_ || this.noventraSync_.syncing) return 'Syncing workspace settings…';
    if (this.noventraSync_.conflict) return 'Both devices changed. Choose which version to keep.';
    if (!this.noventraSync_.configured) return 'Workspace sync is off.';
    if (this.noventraSync_.error) return 'Sync needs attention. Your local work is retained.';
    if (this.noventraSync_.dirty) return 'Local changes are waiting to sync.';
    if (this.noventraSync_.last_success) {
      return `Last synced ${new Date(this.noventraSync_.last_success).toLocaleString()}`;
    }
    return 'Connected. Waiting for the first completed sync.';
  }

