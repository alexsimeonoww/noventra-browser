  private async runWorkspaceSync_(action: string, payload: object = {}) {
    if ((this.noventraSyncBusy_ && action !== 'disconnect') ||
        this.noventraSyncDisconnecting_) return;
    const operation = ++this.workspaceSyncAction_;
    ++this.workspaceSyncGeneration_;
    this.noventraSyncBusy_ = true;
    this.noventraSyncDisconnecting_ = action === 'disconnect';
    this.noventraSyncError_ = '';
    this.workspaceSyncErrorAt_ = null;
    try {
      const result = await sendWithPromise<NoventraSyncStatus&{recovery_key?: string}>(
          'noventraWorkspaceSync', action, payload);
      if (!this.isConnected || operation !== this.workspaceSyncAction_) return;
      const {recovery_key: recoveryKey, ...status} = result;
      this.noventraSync_ = status;
      if (action === 'create' && recoveryKey) {
        this.noventraSyncShowRecovery_ = false;
        this.noventraSyncRecovery_ = recoveryKey;
      }
      if (action === 'disconnect') {
        this.noventraSyncRecovery_ = '';
        this.noventraSyncShowRecovery_ = false;
      }
      await this.refreshSpaces_();
    } catch (error) {
      if (this.isConnected && operation === this.workspaceSyncAction_) {
        this.noventraSyncError_ = this.workspaceSyncErrorMessage_(String(error));
        this.workspaceSyncErrorAt_ = this.workspaceSyncStatusSignature_(this.noventraSync_);
      }
    } finally {
      if (this.isConnected && operation === this.workspaceSyncAction_) {
        this.noventraSyncBusy_ = false;
        this.noventraSyncDisconnecting_ = false;
        void this.refreshWorkspaceSync_();
        await this.updateComplete;
        this.shadowRoot.querySelector<HTMLElement>(this.noventraSyncRecovery_ ?
            '#noventraSyncRecoveryKey' : this.noventraSync_.configured ?
            '#noventraSyncNow' : '#noventraSyncOrigin')?.focus();
      }
    }
  }

