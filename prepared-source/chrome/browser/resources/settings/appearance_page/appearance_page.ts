  private async saveNoventraBarVisibility_(
      mode: BarVisibility, control: HTMLElement) {
    if (this.noventraBarVisibilityDisabled_()) {
      return;
    }
    this.noventraBarVisibilityPending_ = true;
    this.noventraBarVisibilityError_ = '';
    try {
      // These native preferences are independent of the layout draft. Pin the
      // persistent group first, unpin the hidden group next, enable Zen last.
      // Never enable Zen with stale dormant pins and hide an unintended bar.
      const writes: Array<[typeof BAR_VISIBILITY_PREFS[number], boolean]> = [];
      if (mode !== 'visible') {
        const pins: Array<[typeof BAR_VISIBILITY_PREFS[number], boolean]> = [
          [BAR_VISIBILITY_PREFS[1], !['sidebars', 'all'].includes(mode)],
          [BAR_VISIBILITY_PREFS[2], !['top', 'all'].includes(mode)],
        ];
        writes.push(...pins.filter(([, value]) => value));
        writes.push(...pins.filter(([, value]) => !value));
      }
      writes.push([BAR_VISIBILITY_PREFS[0], mode !== 'visible']);
      for (const [key, value] of writes) {
        const pref = await chrome.settingsPrivate.getPref(key) as
            PrefObject<boolean>;
        if (pref.value === value) {
          continue;
        }
        if (!this.barVisibilityPrefsEditable_([pref]) ||
            !await chrome.settingsPrivate.setPref(key, value)) {
          throw new Error('Visibility preference rejected');
        }
      }
    } catch {
      // A previous write may have succeeded. Do not undo a concurrent change
      // in another Settings window or imply these three writes are atomic.
      this.noventraBarVisibilityError_ =
          'Couldn’t save all visibility settings. Review the current choices and try again.';
    } finally {
      try {
        const prefs = await Promise.all(BAR_VISIBILITY_PREFS.map(
            key => chrome.settingsPrivate.getPref(key))) as PrefObject<boolean>[];
        [this.zenModePref_, this.zenSidebarPinnedPref_, this.zenTopPinnedPref_] =
            prefs;
        if (this.noventraBarVisibilityMode_() !== mode) {
          this.noventraBarVisibilityError_ =
              'The visibility settings changed. Review the current choices and try again.';
        }
      } catch {
        this.zenModePref_ = undefined;
        this.zenSidebarPinnedPref_ = undefined;
        this.zenTopPinnedPref_ = undefined;
        this.noventraBarVisibilityError_ =
            'Couldn’t read the current visibility settings. Reopen Settings to try again.';
      }
      this.noventraBarVisibilityPending_ = false;
      await this.updateComplete;
      // Disabling a focused control can blur to the document. Restore only
      // that fallback; a new focus may be in another component's shadow tree
      // (for example Settings search), not in this page's shadow root.
      let focused = document.activeElement;
      while (focused?.shadowRoot?.activeElement) {
        focused = focused.shadowRoot.activeElement;
      }
      if (control.isConnected && document.hasFocus() &&
          (!focused || focused === document.body ||
           focused === document.documentElement)) {
        control.focus({preventScroll: true});
      }
    }
  }

