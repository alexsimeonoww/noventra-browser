  override currentRouteChanged(newRoute: Route, oldRoute?: Route) {
    // Query-only section updates must not replace the route origin used by
    // SettingsViewMixinLit to restore focus after returning from Fonts.
    if (newRoute !== oldRoute) {
      super.currentRouteChanged(newRoute, oldRoute);
    }
    if (newRoute === routes.FONTS || oldRoute === routes.FONTS) {
      this.noventraSection_ = 'customizeAppearance';
      this.noventraPageDisplayOpen_ = true;
      if (newRoute === routes.APPEARANCE) {
        const router = Router.getInstance();
        const params = router.getQueryParameters();
        if (params.get('section') !== 'appearance') {
          params.set('section', 'appearance');
          router.updateRouteParams(params);
        }
      }
    } else if (newRoute === routes.APPEARANCE) {
      const section = Router.getInstance().getQueryParameters().get('section');
      if (section && Object.hasOwn(NOVENTRA_SECTIONS, section)) {
        this.noventraSection_ =
            NOVENTRA_SECTIONS[section as keyof typeof NOVENTRA_SECTIONS];
      }
    }
  }

