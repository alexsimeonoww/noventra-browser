  private validateSpaceName_(name: string, field: string): string|null {
    // Match base::TrimWhitespaceASCII and std::string::size in the handler.
    // String.trim()/maxlength count different whitespace and UTF-16 units.
    const trimmed = name.replace(/^[\t\n\v\f\r ]+|[\t\n\v\f\r ]+$/g, '');
    if (!trimmed || new TextEncoder().encode(trimmed).length > 160) {
      this.noventraSpaceErrorFor_ = field;
      this.noventraError_ = !trimmed ? 'Enter a space name.' :
          'That space name is too long. Try a shorter name.';
      return null;
    }
    return trimmed;
  }

