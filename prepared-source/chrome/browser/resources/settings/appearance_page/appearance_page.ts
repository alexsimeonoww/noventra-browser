  private async refreshWorkspaceSync_() {
    if (this.workspaceSyncPoll_ !== null) {
      window.clearTimeout(this.workspaceSyncPoll_);
      this.workspaceSyncPoll_ = null;
    }
    const details = this.shadowRoot?.querySelector<HTMLDetailsElement>('#noventraWorkspaceSync');
    if (!this.isConnected || document.visibilityState !== 'visible' ||
        !details?.open || !details.checkVisibility()) return;
    const generation = ++this.workspaceSyncGeneration_;
    try {
      const status = await sendWithPromise<NoventraSyncStatus>(
          'noventraWorkspaceSync', 'status', {});
      if (this.isConnected && generation === this.workspaceSyncGeneration_) {
        if (this.workspaceSyncErrorAt_ !== null && (status.error ||
            this.workspaceSyncStatusSignature_(status) !== this.workspaceSyncErrorAt_)) {
          // Once native status acknowledges or supersedes an operation error,
          // render that authoritative status instead of a stale local alert.
          this.noventraSyncError_ = '';
          this.workspaceSyncErrorAt_ = null;
        }
        this.noventraSync_ = status;
        this.noventraSyncAvailable_ = true;
      }
    } catch (error) {
      if (this.isConnected && generation === this.workspaceSyncGeneration_) {
        this.noventraSyncAvailable_ = false;
        this.noventraSyncError_ = this.workspaceSyncErrorMessage_(String(error));
        this.workspaceSyncErrorAt_ = '';
      }
    } finally {
      if (this.isConnected && generation === this.workspaceSyncGeneration_) {
        this.workspaceSyncPoll_ = window.setTimeout(() => {
          this.workspaceSyncPoll_ = null;
          void this.refreshWorkspaceSync_();
        }, 2000);
      }
    }
  }

