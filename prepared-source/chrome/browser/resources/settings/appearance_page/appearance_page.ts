  private async refreshSpaces_() {
    if (this.noventraSpacesPending_ || this.spacesLoading_) {
      this.spacesRefreshRequested_ = true;
      return;
    }
    this.spacesLoading_ = true;
    this.spacesRefreshRequested_ = false;
    const generation = this.spacesMutationGeneration_;
    try {
      const spaces = await sendWithPromise<NoventraSpace[]>(
          'noventraSpaces', 'list', '', '');
      // A list requested before a mutation must not overwrite its response.
      if (this.isConnected && generation === this.spacesMutationGeneration_) {
        this.noventraSpaces_ = spaces;
        this.clearSpaceError_('refresh');
        void this.refreshWorkspaceTools_();
      }
    } catch (error) {
      if (this.isConnected && generation === this.spacesMutationGeneration_ &&
          !this.noventraError_) {
        this.noventraError_ = `Could not refresh spaces: ${String(error)}`;
        this.noventraSpaceErrorFor_ = 'refresh';
      }
    } finally {
      this.spacesLoading_ = false;
      if (this.spacesRefreshRequested_ && !this.noventraSpacesPending_ &&
          this.isConnected) {
        void this.refreshSpaces_();
      }
    }
  }

  private async updateSpaces_(
      action: 'create'|'rename'|'switch'|'move-before'|'move-after'|'archive'|'restore'|'appearance',
      id: string = '', name: string = '') {
    // Set synchronously, before sending: repeated clicks/Enter in the same
    // render frame must not create multiple native spaces.
    if (this.noventraSpacesPending_) {
      return false;
    }
    this.noventraSpacesPending_ = true;
    this.noventraSpaceStatus_ = '';
    ++this.spacesMutationGeneration_;
    const field = action === 'rename' ? `rename:${id}` : action;
    try {
      this.noventraSpaces_ = await sendWithPromise<NoventraSpace[]>(
          'noventraSpaces', action, id, name);
      this.clearSpaceError_(field);
      this.clearSpaceError_('refresh');
      this.clearSpaceError_('switch');
      return true;
    } catch (error) {
      this.noventraError_ = `Could not ${action} space: ${String(error)}`;
      this.noventraSpaceErrorFor_ = field;
      return false;
    } finally {
      this.noventraSpacesPending_ = false;
      if (this.spacesRefreshRequested_ && this.isConnected) {
        void this.refreshSpaces_();
      }
    }
  }

