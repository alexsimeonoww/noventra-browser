def require(condition, message):
    if not condition:
        raise ValueError(message)


def relative(name):
    require(isinstance(name, str) and name and not name.startswith('/')
            and '\\' not in name and ':' not in name
            and all(part not in ('', '.', '..') for part in name.split('/'))
            and not any(ord(c) < 32 or ord(c) == 127 for c in name),
            f'Unsafe relative path: {name!r}')
    return Path(name)


def sha(path):
    before = path.lstat()
    require(stat.S_ISREG(before.st_mode), f'Expected regular file: {path}')
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(descriptor, 'rb') as stream:
        opened = os.fstat(stream.fileno())
        require(stat.S_ISREG(opened.st_mode)
                and (opened.st_dev, opened.st_ino) == (before.st_dev, before.st_ino),
                f'Input changed while opening: {path}')
        digest = hashlib.file_digest(stream, 'sha256').hexdigest()
    after = path.lstat()
    require((before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns,
             before.st_ctime_ns, before.st_mode) ==
            (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns,
             after.st_ctime_ns, after.st_mode), f'Input changed while reading: {path}')
    return digest


def inventory(root):
    """Canonical content inventory; permit only relative, internal bundle links."""
    root = Path(root)
    require(not root.is_symlink() and root.is_dir(), f'Expected real directory: {root}')
    resolved = root.resolve(strict=True)
    result = {}
    def failed_walk(error):
        raise error

    for directory, dirs, files in os.walk(root, followlinks=False, onerror=failed_walk):
        for name in sorted(dirs + files):
            path = Path(directory) / name
            key = path.relative_to(root).as_posix()
            relative(key)
            info = path.lstat()
            require(not info.st_mode & (stat.S_ISUID | stat.S_ISGID), f'Set-id file: {path}')
            if stat.S_ISLNK(info.st_mode):
                target = os.readlink(path)
                require(not os.path.isabs(target), f'Absolute symlink: {path}')
                require(path.resolve(strict=True).is_relative_to(resolved), f'Escaping symlink: {path}')
                result[key] = {'type': 'symlink', 'target': target}
            elif stat.S_ISDIR(info.st_mode):
                result[key] = {'type': 'directory', 'mode': oct(stat.S_IMODE(info.st_mode))}
            else:
                require(stat.S_ISREG(info.st_mode), f'Special file: {path}')
                result[key] = {'type': 'file', 'mode': oct(stat.S_IMODE(info.st_mode)),
                               'size': info.st_size, 'sha256': sha(path)}
    return result


def inventory_digest(root):
    """Shared with the native build-receipt producer; no platform dependencies."""
    return hashlib.sha256(json.dumps(inventory(root), sort_keys=True,
                                    separators=(',', ':')).encode('utf-8')).hexdigest()


def json_object(path):
    def unique(pairs):
        value = {}
        for key, item in pairs:
            require(key not in value, f'Duplicate JSON key: {key}')
            value[key] = item
        return value

    require(not path.is_symlink() and path.is_file(), f'Expected regular JSON: {path}')
    value = json.loads(path.read_bytes(), object_pairs_hook=unique,
                       parse_constant=lambda x: require(False, f'Invalid JSON constant: {x}'))
    require(isinstance(value, dict), f'Expected JSON object: {path}')
    return value


def child(root, name):
    path = root / relative(name)
    require(path.resolve(strict=True).is_relative_to(root.resolve(strict=True)),
            f'Path escapes input root: {name}')
    # Receipt evidence and generated signing inputs must have no symlink parents.
    current = root
    for part in relative(name).parts:
        current /= part
        require(not current.is_symlink(), f'Symlink input: {current}')
    return path


def validate_receipt(receipt_path, app):
    receipt_path = Path(receipt_path)
    receipt = json_object(receipt_path)
    require(type(receipt.get('format')) is int and receipt['format'] == 1
            and receipt.get('kind') == 'noventra-macos-build',
            'Expected a native Noventra format-1 build receipt')
    require(all(isinstance(receipt.get(key), dict) for key in
                ('target', 'app', 'source', 'gates', 'evidence', 'signing_inputs')),
            'Receipt requires target/app/source/gates/evidence/signing_inputs objects')
    require(receipt.get('target') == {'os': 'mac', 'cpu': 'arm64', 'component_build': False},
            'Receipt must describe a static native mac/arm64 build')
    require(receipt['target']['component_build'] is False, 'Component-build gate must be false')
    require(receipt.get('app', {}).get('name') == 'Noventra.app'
            and receipt['app'].get('bundle_id') == BUNDLE_ID, 'Receipt has wrong product identity')
    require(isinstance(receipt['source'].get('manifest_sha256'), str)
            and re.fullmatch(r'[0-9a-f]{64}', receipt['source']['manifest_sha256']),
            'Receipt requires the exact source-manifest SHA-256')
    require(receipt['app'].get('tree_sha256') == inventory_digest(app), 'Build bundle inventory mismatch')
    for gate in GATES:
        require(receipt.get('gates', {}).get(gate) is True, f'Missing successful gate: {gate}')
        evidence = receipt.get('evidence', {}).get(gate, {})
        require(isinstance(evidence, dict), f'Expected gate evidence object: {gate}')
        report_path = child(receipt_path.parent, evidence.get('path'))
        require(evidence.get('sha256') == sha(report_path), f'Gate evidence hash mismatch: {gate}')
        report = json_object(report_path)
        require(report.get('format') == 1 and report.get('gate') == gate
                and report.get('status') == 'passed', f'Gate evidence did not pass: {gate}')
    inputs = receipt.get('signing_inputs', {})
    signing = child(receipt_path.parent, inputs.get('path'))
    require(inputs.get('tree_sha256') == inventory_digest(signing), 'Signing-input inventory mismatch')
    for name in (*ENTITLEMENTS, 'signing/parts.py', 'signing/build_props_config.py',
                 'signing/chromium_config.py'):
        require(child(signing, name).is_file(), f'Missing generated signing input: {name}')
    return receipt, signing


THIN = {b'\xcf\xfa\xed\xfe': '<', b'\xfe\xed\xfa\xcf': '>'}
FAT = {b'\xca\xfe\xba\xbe': ('>', False), b'\xbe\xba\xfe\xca': ('<', False),
       b'\xca\xfe\xba\xbf': ('>', True), b'\xbf\xba\xfe\xca': ('<', True)}
ARCH = {0x100000c: 'arm64', 0x1000007: 'x86_64'}


def macho_architectures(path):
    """Read Mach-O architecture headers without shell tools (unit-testable)."""
    with path.open('rb') as stream:
        size = path.stat().st_size
        magic = stream.read(4)
        require(magic != b'\x7fELF', f'Linux ELF in macOS bundle: {path}')
        if magic in THIN:
            header = stream.read(28)
            require(len(header) == 28, f'Truncated Mach-O: {path}')
            cpu, _, filetype, *_ = struct.unpack(THIN[magic] + '7I', header)
            require(cpu in ARCH and filetype in (2, 6, 8), f'Unsupported Mach-O: {path}')
            return {ARCH[cpu]}
        if magic not in FAT:
            require(magic not in (b'\xce\xfa\xed\xfe', b'\xfe\xed\xfa\xce'),
                    f'32-bit Mach-O unsupported: {path}')
            return set()
        endian, wide = FAT[magic]
        count_bytes = stream.read(4)
        require(len(count_bytes) == 4, f'Truncated universal Mach-O: {path}')
        count = struct.unpack(endian + 'I', count_bytes)[0]
        require(0 < count <= 16, f'Invalid universal Mach-O count: {path}')
        width = 32 if wide else 20
        table = stream.read(count * width)
        require(len(table) == count * width, f'Truncated universal table: {path}')
        found, ranges = set(), []
        for index in range(count):
            entry = struct.unpack(endian + ('IIQQII' if wide else 'IIIII'),
                                  table[index * width:(index + 1) * width])
            cpu, _, offset, length, *_ = entry
            require(cpu in ARCH and ARCH[cpu] not in found and length >= 32
                    and offset >= 8 + count * width and offset + length <= size,
                    f'Invalid universal Mach-O slice: {path}')
            require(all(offset + length <= left or offset >= right for left, right in ranges),
                    f'Overlapping universal Mach-O slices: {path}')
            stream.seek(offset)
            slice_magic = stream.read(4)
            header = stream.read(28)
            require(slice_magic in THIN and len(header) == 28, f'Invalid Mach-O slice: {path}')
            slice_cpu, _, filetype, *_ = struct.unpack(THIN[slice_magic] + '7I', header)
            require(slice_cpu == cpu and filetype in (2, 6, 8), f'Mach-O slice CPU mismatch: {path}')
            found.add(ARCH[cpu])
            ranges.append((offset, offset + length))
        return found


def bundle_executable(bundle):
    if bundle.suffix == '.app':
        info_path, executable_dir = bundle / 'Contents/Info.plist', bundle / 'Contents/MacOS'
    else:
        info_path, executable_dir = bundle / 'Resources/Info.plist', bundle
    info = plistlib.loads(info_path.read_bytes())
    require(isinstance(info, dict), f'Expected bundle metadata object: {bundle}')
    name = info.get('CFBundleExecutable')
    require(isinstance(name, str) and relative(name).name == name, f'Invalid bundle executable: {bundle}')
    executable = executable_dir / name
    require(executable.resolve(strict=True).is_relative_to(bundle.resolve(strict=True)),
            f'Bundle executable escapes: {bundle}')
    require(executable.is_file() and executable.stat().st_mode & 0o111,
            f'Missing executable: {bundle}')
    return info, executable


def validate_bundle(app):
    app = Path(app)
    require(app.name == 'Noventra.app', 'Expected genuine Noventra.app, not a renamed product')
    files = inventory(app)
    info, main = bundle_executable(app)
    require(info.get('CFBundleIdentifier') == BUNDLE_ID
            and info.get('CFBundleName') == 'Noventra' and main.name == 'Noventra'
            and info.get('CFBundlePackageType') == 'APPL', 'Wrong top-level Noventra bundle identity')
    require(isinstance(info.get('CFBundleShortVersionString'), str)
            and re.fullmatch(r'[0-9]+(?:\.[0-9]+){3}', info['CFBundleShortVersionString']),
            'Expected native four-part browser version')
    require((app / 'Contents/Resources/Assets.car').is_file()
            and (app / 'Contents/Resources/Assets.car').stat().st_size > 0, 'Missing compiled Assets.car')
    framework = app / 'Contents/Frameworks/Noventra Framework.framework'
    framework_info, framework_binary = bundle_executable(framework)
    require(framework_info.get('CFBundleIdentifier') == BUNDLE_ID + '.framework',
            'Wrong Noventra framework identity')
    install_resource = (framework_binary.resolve().parent / 'Resources/install.sh').relative_to(
        app.resolve()).as_posix()
    code, scripts = {}, {}
    for name, entry in files.items():
        path = app / name
        require('sparkle' not in name.lower(), f'Sparkle is unsupported in test packages: {name}')
        if entry['type'] == 'directory' and path.suffix == '.app':
            helper, executable = bundle_executable(path)
            require(str(helper.get('CFBundleIdentifier', '')).startswith(BUNDLE_ID + '.')
                    and path.stem.startswith('Noventra Helper') and executable.name == path.stem,
                    f'Wrong helper bundle identity: {name}')
        if entry['type'] != 'file':
            continue
        if name == install_resource:
            require(entry['sha256'] == INSTALL_SCRIPT_SHA256,
                    f'Pinned Chromium install resource changed: {name}')
            require(int(entry['mode'], 8) & 0o111, f'Missing install resource executable mode: {name}')
            scripts[name] = entry['sha256']
            continue
        if path.name.endswith('.plist'):
            properties = plistlib.loads(path.read_bytes())
            require(not isinstance(properties, dict) or not any(properties.get(key) for key in
                            ('SUFeedURL', 'SUEnableAutomaticChecks', 'SUAutomaticallyUpdate')),
                    f'Sparkle update configuration is enabled: {name}')
        architectures = macho_architectures(path)
        if architectures:
            require('arm64' in architectures, f'ARM64 slice required: {name}')
            code[name] = sorted(architectures)
        else:
            require(not int(entry['mode'], 8) & 0o111, f'Unsupported non-Mach-O executable: {name}')
    require(main.resolve().relative_to(app.resolve()).as_posix() in code,
            'Browser executable is not ARM64 Mach-O')
    return {'files': files, 'code': code, 'script_resources': scripts,
            'version': info.get('CFBundleShortVersionString')}


