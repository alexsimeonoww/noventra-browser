def validate_plan(app, signing, plan, code):
    require(isinstance(plan, list) and plan, 'Missing upstream signing plan')
    targets, names = set(), set()
    for part in plan:
        require(isinstance(part, dict) and isinstance(part.get('name'), str), 'Invalid signing part')
        require(part.get('name') not in names, 'Duplicate signing part')
        names.add(part.get('name'))
        location = relative(part.get('path'))
        require(location.parts[0] == 'Noventra.app', 'Signing part escapes Noventra.app')
        target = app.parent / location
        require(target.resolve(strict=True).is_relative_to(app.resolve()), 'Escaping signing target')
        executable = bundle_executable(target)[1] if target.is_dir() else target
        key = executable.resolve(strict=True).relative_to(app.resolve()).as_posix()
        require(key in code and key not in targets, f'Unknown/duplicate signing target: {key}')
        targets.add(key)
        require(isinstance(part.get('options'), str)
                and set(part['options'].split(',')) <= {'', 'restrict', 'library', 'runtime', 'kill'},
                'Unknown upstream signing flags')
        entitlement = part.get('entitlements')
        require(isinstance(part.get('sign_with_identifier'), bool)
                and isinstance(part.get('identifier'), str)
                and re.fullmatch(r'[A-Za-z0-9_.-]+', part['identifier']), 'Invalid signing identifier')
        if entitlement:
            require(entitlement in ENTITLEMENTS, 'Unknown upstream entitlement file')
            properties = plistlib.loads(child(signing, entitlement).read_bytes())
            require(isinstance(properties, dict), 'Invalid entitlement plist')
            require(not any(properties.get(key) for key in (
                'com.apple.security.cs.disable-library-validation',
                'com.apple.security.cs.allow-unsigned-executable-memory',
                'com.apple.security.cs.disable-executable-page-protection',
                'com.apple.security.cs.allow-dyld-environment-variables',
                'com.apple.security.get-task-allow')), 'Generated entitlement weakens runtime protection')
        require(isinstance(part.get('requirements', ''), str), 'Invalid generated requirements')
        expected_entitlement = ('app-entitlements.plist' if part['name'] == 'app' else
            'helper-renderer-entitlements.plist' if 'renderer-app' in part['name'] else
            'helper-gpu-entitlements.plist' if 'gpu-app' in part['name'] else None)
        require(entitlement == expected_entitlement, f'Unexpected Chromium entitlements: {part["name"]}')
        if expected_entitlement and part['name'] != 'app':
            require('library' not in part['options'].split(',')
                    and properties.get('com.apple.security.cs.allow-jit') is True,
                    f'JIT helper signing flags/entitlements are incompatible: {part["name"]}')
        expected_flags = (set() if part['name'] == 'framework' or part['name'].endswith('.dylib')
                          else {'kill', 'restrict', 'runtime'} | (
                              set() if expected_entitlement and part['name'] != 'app' else {'library'}))
        require(set(filter(None, part['options'].split(','))) == expected_flags,
                f'Generated protection flags differ: {part["name"]}')
    require(names >= {'app', 'framework', 'helper-app', 'helper-renderer-app', 'helper-gpu-app'},
            'Incomplete Chromium signing plan')
    require(targets == set(code), f'Unplanned Mach-O code: {sorted(set(code) - targets)}')
    return sorted(plan, key=lambda p: (p['name'] == 'app', p['name'] == 'framework'))


def select_signing_identity(selector):
    require(isinstance(selector, str) and re.fullmatch(r'[0-9A-Fa-f]{40}', selector),
            'An existing Apple-issued signing identity SHA-1 is required; ad-hoc signing cannot satisfy library validation')
    result = subprocess.run(['/usr/bin/security', 'find-identity', '-v', '-p', 'codesigning'],
                            capture_output=True, timeout=15)
    require(result.returncode == 0, 'Cannot enumerate available code-signing identities')
    matches = re.findall(r'(?m)^\s*\d+\) ([0-9A-Fa-f]{40}) "([^"]+)"', result.stdout.decode())
    name = next((name for fingerprint, name in matches if fingerprint.upper() == selector.upper()), None)
    require(name is not None, 'Selected code-signing identity is not available with a valid private key')
    kind = next((kind for kind in ('Apple Development', 'Mac Developer', 'Developer ID Application')
                 if name.startswith(kind + ':')), None)
    require(kind is not None, 'Selected identity is not an appropriate Apple-issued application signing identity')
    return {'sha1': selector.upper(), 'type': kind}


def signing_command(target, part, signing, identity):
    command = ['/usr/bin/codesign', '--force', '--sign', identity, '--timestamp=none']
    if part['options']:
        command += ['--options', part['options']]
    if part['sign_with_identifier']:
        command += ['--identifier', part['identifier']]
    if part.get('requirements'):
        command += ['--requirements', '=' + part['requirements']]
    if part['entitlements']:
        command += ['--entitlements', child(signing, part['entitlements'])]
    return [*command, target]


def apple_requirement(identity):
    return f'anchor apple generic and certificate leaf = H"{identity["sha1"]}"'


def signature_team(display):
    match = re.search(r'(?m)^TeamIdentifier=([A-Z0-9]{10})$', display.decode())
    require(match is not None, 'Apple signing produced no genuine TeamIdentifier')
    return match.group(1)


def preflight_signing_identity(identity, executable, parent, run):
    with tempfile.TemporaryDirectory(prefix='.noventra-signing-', dir=parent) as temporary:
        probe = Path(temporary) / 'signing-probe'
        shutil.copy2(executable, probe)
        run(['/usr/bin/codesign', '--force', '--sign', identity['sha1'], '--timestamp=none',
             '--options', 'kill,library,restrict,runtime', probe])
        run(['/usr/bin/codesign', '--verify', '--strict', '-R', apple_requirement(identity), probe])
        display = run(['/usr/bin/codesign', '--display', '--verbose=5', probe], display=True)
        return {**identity, 'team_identifier': signature_team(display)}


def verify_signed_part(target, part, signing, identity, run):
    run(['/usr/bin/codesign', '--verify', '--strict', '--verbose=2', '-R', apple_requirement(identity), target])
    display = run(['/usr/bin/codesign', '--display', '--verbose=5', '--requirements', '-', target], display=True)
    require(signature_team(display) == identity['team_identifier'], f'Signing team differs: {part["name"]}')
    flags = re.search(rb'flags=0x([0-9a-fA-F]+)', display)
    bits = {'kill': 0x200, 'restrict': 0x800, 'library': 0x2000, 'runtime': 0x10000}
    expected = sum(bits[option] for option in part['options'].split(',') if option)
    require(flags is not None and int(flags.group(1), 16) == expected,
            f'Signed protection flags differ: {part["name"]}')
    raw = run(['/usr/bin/codesign', '--display', '--entitlements', ':-', target])
    actual = plistlib.loads(raw) if raw.strip() else {}
    expected_entitlements = plistlib.loads(child(signing, part['entitlements']).read_bytes()) if part['entitlements'] else {}
    require(actual == expected_entitlements, f'Signed entitlements differ: {part["name"]}')


def package(app, build_receipt, output, signing_identity='-'):
    require(sys.platform == 'darwin', 'Packaging requires native macOS; Linux fixtures are validation only')
    identity = select_signing_identity(signing_identity)
    app, build_receipt, output = Path(app).absolute(), Path(build_receipt).absolute(), Path(output).absolute()
    validated = validate_bundle(app)
    receipt_digest = sha(build_receipt)
    receipt, signing = validate_receipt(build_receipt, app)
    source_digest, signing_digest = inventory_digest(app), inventory_digest(signing)
    require(not output.exists() and not output.is_symlink(), 'Output must be a new unique directory')
    require(not output.resolve().is_relative_to(app.resolve())
            and not app.resolve().is_relative_to(output.resolve())
            and not output.resolve().is_relative_to(signing.resolve()), 'Output overlaps package inputs')
    require(not any(parent.suffix == '.app' for parent in (output, *output.parents))
            and not output.resolve().is_relative_to(Path('/Applications'))
            and not output.resolve().is_relative_to(Path('/System/Applications')),
            'Output must not modify Applications or an existing application bundle')
    commands = []

    def run(argv, display=False):
        try:
            process = subprocess.run([str(x) for x in argv], check=False, capture_output=True, timeout=120)
        except subprocess.TimeoutExpired as error:
            raise RuntimeError(f'Command timed out: {argv[0]}; private-key authorization may require the host prompt workflow') from error
        commands.append({'argv': [str(x) for x in argv], 'returncode': process.returncode,
                         'stdout': process.stdout.decode('utf-8', 'replace'),
                         'stderr': process.stderr.decode('utf-8', 'replace')})
        if output.is_dir():
            (output / 'commands.json').write_text(json.dumps(commands, indent=2) + '\n')
        require(process.returncode == 0, f'Command failed: {argv[0]}: {process.stderr.decode("utf-8", "replace").strip()}')
        return process.stdout + process.stderr if display else process.stdout

    plan = json.loads(run([sys.executable, '-I', '-B', '-c', PLAN_SCRIPT, signing, identity['sha1']]))
    plan = validate_plan(app, signing, plan, validated['code'])
    identity = preflight_signing_identity(identity, bundle_executable(app)[1], output.parent, run)
    output.mkdir(parents=True, exist_ok=False)
    (output / 'RUNTIME-STATUS.md').write_text(
        'Runtime qualification incomplete. Do not use or distribute any image in this directory.\n'
        'A successful package-receipt.json with runtime_verified=true is required.\n')
    stage, volume, mount, copied = (output / name for name in ('stage', 'volume', 'mount', 'roundtrip'))
    for path in (stage, volume, mount, copied):
        path.mkdir()
    staged = stage / 'Noventra.app'
    run(['/usr/bin/ditto', app, staged])
    require(inventory_digest(staged) == source_digest, 'Staged copy differs from build')
    for part in plan:
        target = stage / relative(part['path'])
        run(signing_command(target, part, signing, identity['sha1']))
        verify_signed_part(target, part, signing, identity, run)
    run(['/usr/bin/codesign', '--verify', '--deep', '--strict', '--verbose=2', staged])
    validate_bundle(staged)
    signed_digest = inventory_digest(staged)
    from qualify_macos import qualify
    runtime = qualify(staged, output / 'staged-runtime')
    require(runtime['passed'], f'Staged runtime qualification failed; see {output / "staged-runtime"}')
    run(['/usr/bin/ditto', staged, volume / 'Noventra.app'])
    require(inventory_digest(volume / 'Noventra.app') == signed_digest, 'DMG input copy differs')
    (volume / 'Applications').symlink_to('/Applications', target_is_directory=True)
    (volume / 'READ ME.txt').write_text(README)
    image = output / 'Noventra-arm64-test.dmg'
    run(['/usr/bin/hdiutil', 'create', '-volname', 'Noventra Test', '-fs', 'HFS+',
         '-srcfolder', volume, '-format', 'UDZO', image])
    run(['/usr/bin/hdiutil', 'verify', image])
    mounted = False
    try:
        attachment = run(['/usr/bin/hdiutil', 'attach', '-readonly', '-nobrowse', '-noautoopen',
                          '-mountpoint', mount, '-plist', image])
        mounted = True
        entities = plistlib.loads(attachment).get('system-entities', [])
        require(any(e.get('mount-point') == str(mount) for e in entities), 'Unexpected DMG mount point')
        require((mount / 'Applications').is_symlink()
                and os.readlink(mount / 'Applications') == '/Applications', 'Missing Applications shortcut')
        require((mount / 'READ ME.txt').read_text() == README, 'DMG test notice differs')
        validate_bundle(mount / 'Noventra.app')
        require(inventory_digest(mount / 'Noventra.app') == signed_digest, 'Mounted app differs')
        installed = copied / 'Noventra.app'
        run(['/usr/bin/ditto', mount / 'Noventra.app', installed])
        validate_bundle(installed)
        run(['/usr/bin/codesign', '--verify', '--deep', '--strict', '--verbose=2', installed])
        require(inventory_digest(installed) == signed_digest, 'Copied-out app differs')
        for part in plan:
            verify_signed_part(copied / relative(part['path']), part, signing, identity, run)
    finally:
        if mounted or os.path.ismount(mount):
            run(['/usr/bin/hdiutil', 'detach', mount])
            require(not os.path.ismount(mount), 'Owned image mount did not detach')
    require(inventory_digest(app) == source_digest and inventory_digest(signing) == signing_digest,
            'Packaging input changed during operation')
    require(sha(build_receipt) == receipt_digest, 'Build receipt changed during operation')
    runtime = qualify(installed, output / 'roundtrip-runtime')
    require(runtime['passed'], f'DMG copied-out runtime qualification failed; see {output / "roundtrip-runtime"}')
    require(inventory_digest(installed) == signed_digest, 'Runtime check modified the copied-out app')
    result = {'format': 1, 'kind': 'noventra-macos-test-package', 'complete': True,
              'ad_hoc_signed': False, 'notarized': False, 'runtime_verified': True,
              'signing_identity': identity, 'runtime_scope': 'headless local JavaScript DOM; isolated incognito profile; mock Keychain',
              'runtime_evidence': {'path': 'roundtrip-runtime/runtime-receipt.json',
                                   'sha256': sha(output / 'roundtrip-runtime/runtime-receipt.json')},
              'app': {'name': 'Noventra.app', 'bundle_id': BUNDLE_ID,
                      'version': validated['version'], 'required_architecture': 'arm64'},
              'build_receipt_sha256': receipt_digest, 'source': receipt['source'],
              'input_bundle_tree_sha256': source_digest, 'signed_bundle_tree_sha256': signed_digest,
              'image': {'name': image.name, 'size': image.stat().st_size, 'sha256': sha(image)},
              'checks': ['signature verification', 'hdiutil verify', 'read-only image reopen',
                         'copied-out bundle identity, ARM64, inventory and signature verification'],
              'script_resources': validated['script_resources'],
              'signing_plan': plan}
    (output / 'package-receipt.json').write_text(json.dumps(result, indent=2) + '\n')
    (output / 'RUNTIME-STATUS.md').write_text(
        'Local headless JavaScript DOM qualification passed on the DMG copy-out.\n'
        'Mock Keychain and fresh incognito profile only. GUI and real Keychain remain unqualified.\n'
        'Not notarized. Not a public release.\n')
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--app', type=Path, required=True)
    parser.add_argument('--build-receipt', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True, help='New unique output directory')
    parser.add_argument('--signing-identity', default='-', help='SHA-1 of an existing Apple Development, Mac Developer or Developer ID Application identity')
    args = parser.parse_args()
    try:
        result = package(args.app, args.build_receipt, args.output, args.signing_identity)
    except (ValueError, OSError, RuntimeError, subprocess.TimeoutExpired, plistlib.InvalidFileException) as error:
        parser.exit(1, f'Packaging failed: {error}\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
